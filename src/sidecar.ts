/**
 * YAML sidecars for STL models: <name>.stl.yaml adjacent to the STL,
 * holding machine facts (size, file date), a local-vision description of
 * the model's collage via Ollama, and an empty human notes block the
 * model never touches. Skip-if-exists makes runs incremental; failures
 * are simply retried on the next run. Local-first: nothing leaves the
 * machine.
 */
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, relative } from "node:path";
import { generateJson, type OllamaOptions } from "./ollama.js";
import { walkStl } from "./collage.js";

const CATEGORIES = [
  "repair-part", "functional-tool", "gift-or-toy",
  "product-design", "upgrade-mod", "household", "unknown",
] as const;

interface Vision {
  description: string;
  category: string;
  tags: string[];
}

const VISION_SCHEMA = {
  type: "object",
  properties: {
    description: {
      type: "string",
      description: "2-3 sentences: what the object is and what it is likely for",
    },
    category: { type: "string", enum: CATEGORIES },
    tags: { type: "array", items: { type: "string" }, minItems: 3, maxItems: 6 },
  },
  required: ["description", "category", "tags"],
};

const prompt = (name: string, cluePath: string): string =>
  `This is a 5-view render collage (top, front, left, right, perspective) ` +
  `of a single 3D-printable STL model.\n` +
  `Filename: ${name}\n` +
  `Path in the archive: ${cluePath}\n` +
  `Treat the filename and folder names as strong clues to the object's ` +
  `identity — they were written by the maker. Decode terse shorthand ` +
  `(e.g. "1.5 sch 40 pip cover" means a cover for 1.5-inch schedule-40 ` +
  `pipe; a numbered folder name often names the project the part belongs ` +
  `to). Reconcile the clues with what you actually see in the renders; ` +
  `if they conflict, say so in the description.\n` +
  `Describe what the object is and what it is likely for (2-3 sentences), ` +
  `pick the best-fitting category (${CATEGORIES.join(" | ")}), ` +
  `and give 3-6 catalog tags.`;

/** Last few path segments — enough context to include the project folder,
 * regardless of where the scan was rooted. */
function cluePath(absStl: string, segments = 4): string {
  return absStl.replaceAll("\\", "/").split("/").filter(Boolean).slice(-segments).join("/");
}

async function describeCollage(
  o: OllamaOptions,
  collage: string,
  stl: string,
): Promise<Vision> {
  const image = readFileSync(collage).toString("base64");
  return generateJson<Vision>(o, prompt(basename(stl), cluePath(stl)), VISION_SCHEMA, { images: [image] });
}

const q = (s: string): string => JSON.stringify(s); // JSON string = valid YAML scalar

function sidecarYaml(stl: string, rel: string, vision: Vision | null, model: string | null): string {
  const st = statSync(stl);
  const lines = [
    "# generated by sifter meta — edit freely; this file is the source of truth",
    `file: ${q(basename(stl))}`,
    `path: ${q(rel.replaceAll("\\", "/"))}`,
    `size_bytes: ${st.size}`,
    `file_date: ${st.mtime.toISOString().slice(0, 10)}  # filesystem mtime; may be data-rescue noise`,
    `described_by: ${model ? q(model) : "null"}`,
    `described_on: ${q(new Date().toISOString().slice(0, 10))}`,
  ];
  if (vision) {
    lines.push(
      `description: ${q(vision.description)}`,
      `category: ${q(vision.category)}`,
      `tags: [${vision.tags.map(q).join(", ")}]`,
    );
  }
  lines.push(
    "notes:            # yours — the model never touches this block",
    '  origin: ""      # when/why it was really made',
    '  for: ""         # who it was for',
    '  story: ""',
  );
  return lines.join("\n") + "\n";
}

export interface MetaOptions {
  vision: boolean;
  limit?: number;
}

export interface MetaResult {
  written: number;
  skipped: number;
  failed: number;
  missingCollage: number;
}

export async function metaBatch(
  root: string,
  ollama: OllamaOptions,
  opts: MetaOptions,
  log: (line: string) => void,
): Promise<MetaResult> {
  const res: MetaResult = { written: 0, skipped: 0, failed: 0, missingCollage: 0 };
  for (const stl of walkStl(root)) {
    const base = basename(stl, extname(stl));
    const dir = dirname(stl);
    const sidecar = join(dir, `${base}.stl.yaml`);
    if (existsSync(sidecar)) { res.skipped++; continue; }
    if (opts.limit && res.written >= opts.limit) {
      log(`limit ${opts.limit} reached`);
      return res;
    }
    const rel = relative(root, stl);
    let vision: Vision | null = null;
    let model: string | null = null;
    if (opts.vision) {
      const collage = join(dir, `${base}-collage.png`);
      if (!existsSync(collage)) {
        res.missingCollage++;
        log(`NOCOLLAGE ${rel}`);
        continue;
      }
      try {
        vision = await describeCollage(ollama, collage, stl);
        model = ollama.model;
      } catch (err) {
        res.failed++;
        log(`FAIL ${rel}: ${(err as Error).message}`);
        continue;
      }
    }
    writeFileSync(sidecar, sidecarYaml(stl, rel, vision, model), "utf8");
    res.written++;
    log(`OK   ${rel}${vision ? `  [${vision.category}]` : ""}`);
  }
  return res;
}

import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import type { Description, Manifest, Ranking } from "./types.js";
import type { DupeResult } from "./dupes.js";
import type { SifterConfig } from "./config.js";

function fmtSize(n: number): string {
  if (n > 1024 * 1024 * 1024) return (n / (1024 * 1024 * 1024)).toFixed(1) + " GB";
  if (n > 1024 * 1024) return (n / (1024 * 1024)).toFixed(1) + " MB";
  if (n > 1024) return (n / 1024).toFixed(1) + " KB";
  return n + " B";
}

export function writeReports(
  m: Manifest,
  dupes: DupeResult,
  descriptions: Description[],
  rankings: Ranking[],
  cfg: SifterConfig,
): string[] {
  mkdirSync(cfg.out, { recursive: true });
  const written: string[] = [];
  const descByPath = new Map(descriptions.map((d) => [d.path, d]));
  const header =
    `> Generated by Sifter at privacy tier T${cfg.tier} ` +
    `(${cfg.tier === 0 ? "folder names only" : cfg.tier === 1 ? "folder + file names and metadata" : "names, metadata, and sampled text content"}). ` +
    `All inference ran locally (${cfg.model}). Root: ${m.root}\n\n`;

  // --- report.md: ranked review queue ---
  const ranked = [...rankings].sort((a, b) => b.score - a.score);
  let md = `# Sifter report\n\n${header}`;
  md += `| Score | Action | Folder | Why |\n|---|---|---|---|\n`;
  for (const r of ranked) {
    const novel = r.novelty ? ` **[NOVEL${r.noveltyName ? ": " + r.noveltyName : ""}]**` : "";
    md += `| ${r.score} | ${r.action} | \`/${r.path}\`${novel} | ${r.rationale.replaceAll("|", "/")} |\n`;
  }
  md += `\n## Descriptions\n\n`;
  for (const r of ranked) {
    const d = descByPath.get(r.path);
    if (d) md += `- **/${r.path}** — ${d.description}\n`;
  }
  const p1 = join(cfg.out, "report.md");
  writeFileSync(p1, md);
  written.push(p1);

  // --- dupes.md ---
  let dd = `# Duplicate analysis\n\n${header}`;
  dd += `## Identical clusters (${dupes.clusters.length})\n\n`;
  for (const c of dupes.clusters.sort((a, b) => b.totalSize - a.totalSize).slice(0, 200)) {
    dd += `- **/${c.representative}** (${c.fileCount} files, ${fmtSize(c.totalSize)}) — identical copies:\n`;
    for (const copy of c.copies) dd += `  - /${copy}\n`;
  }
  dd += `\n## Same-name folder relationships (${dupes.pairs.length})\n\n`;
  for (const p of dupes.pairs.slice(0, 300)) {
    if (p.kind === "superset") {
      dd += `- **superset**: \`/${p.a}\` contains everything in \`/${p.b}\` plus ${p.onlyInA} more entries` +
        (p.onlyInASample.length ? ` (extra: ${p.onlyInASample.join(", ")})` : "") + `\n`;
    } else if (p.kind === "diverged") {
      dd += `- **diverged** (J=${p.jaccard.toFixed(2)}): \`/${p.a}\` vs \`/${p.b}\` — ${p.onlyInA} unique left, ${p.onlyInB} unique right. **Review both.**` +
        (p.onlyInASample.length ? ` Left-only sample: ${p.onlyInASample.join(", ")}.` : "") +
        (p.onlyInBSample.length ? ` Right-only sample: ${p.onlyInBSample.join(", ")}.` : "") + `\n`;
    } else if (p.kind === "name-collision") {
      dd += `- **name-collision**: \`/${p.a}\` vs \`/${p.b}\` share a name but not content (J=${p.jaccard.toFixed(2)})\n`;
    }
  }
  const p2 = join(cfg.out, "dupes.md");
  writeFileSync(p2, dd);
  written.push(p2);

  // --- novel.md ---
  const novel = ranked.filter((r) => r.novelty);
  let nv = `# Novelty candidates\n\n${header}Folders that look like the owner's own substantial work but are not in the profile's known-projects list.\n\n`;
  for (const r of novel) {
    const d = descByPath.get(r.path);
    nv += `- **/${r.path}**${r.noveltyName ? ` — apparent name: **${r.noveltyName}**` : ""} (score ${r.score})\n  ${d?.description ?? ""}\n`;
  }
  if (novel.length === 0) nv += `(none flagged)\n`;
  const p3 = join(cfg.out, "novel.md");
  writeFileSync(p3, nv);
  written.push(p3);

  // --- report.json ---
  const p4 = join(cfg.out, "report.json");
  writeFileSync(p4, JSON.stringify({
    root: m.root, tier: cfg.tier, model: cfg.model, generatedAt: new Date().toISOString(),
    rankings: ranked, descriptions, dupes: { clusters: dupes.clusters, pairs: dupes.pairs },
  }, null, 2));
  written.push(p4);

  return written;
}

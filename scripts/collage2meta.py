#!/usr/bin/env python3
"""collage2meta.py — generate adjacent YAML sidecars for STL models.

For every *.stl under <folder> that has a rendered <name>-collage.png,
write <name>.stl.yaml next to it: machine facts (size, file date) plus a
local-vision description via Ollama, and an empty human block for hand
notes. Skips files whose sidecar already exists, so it is safe to
interrupt and re-run. Local-first: nothing leaves the machine.

Usage:
  python collage2meta.py <folder> [--model gemma4:12b] [--no-vision]
                         [--limit N] [--ollama http://localhost:11434]
"""
import argparse, base64, datetime, json, os, sys, urllib.request

PROMPT = (
    "This is a 5-view render collage (top, front, left, right, perspective) "
    "of a single 3D-printable STL model. Filename: {name}. "
    "Reply in exactly this format:\n"
    "description: <2-3 sentences: what the object is and what it is likely for>\n"
    "category: <one of: repair-part | functional-tool | gift-or-toy | "
    "product-design | upgrade-mod | household | unknown>\n"
    "tags: <3-6 comma-separated keywords>"
)

def vision(ollama, model, image_path, name):
    b64 = base64.b64encode(open(image_path, "rb").read()).decode()
    req = urllib.request.Request(
        ollama.rstrip("/") + "/api/generate",
        data=json.dumps({"model": model, "prompt": PROMPT.format(name=name),
                         "images": [b64], "stream": False,
                         "keep_alive": "30m"}).encode(),
        headers={"Content-Type": "application/json"})
    resp = json.loads(urllib.request.urlopen(req, timeout=600).read())
    return resp["response"].strip()

def parse_reply(text):
    out = {"description": "", "category": "unknown", "tags": []}
    for line in text.splitlines():
        line = line.strip()
        low = line.lower()
        if low.startswith("description:"):
            out["description"] = line.split(":", 1)[1].strip()
        elif low.startswith("category:"):
            out["category"] = line.split(":", 1)[1].strip().strip("<>").lower()
        elif low.startswith("tags:"):
            out["tags"] = [t.strip() for t in line.split(":", 1)[1].split(",") if t.strip()]
    if not out["description"]:  # model went off-format; keep raw text
        out["description"] = " ".join(text.split())
    return out

def q(s):  # YAML double-quoted scalar
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

def write_yaml(path, stl, rel, meta, vis, model):
    lines = ["# generated by collage2meta.py — edit freely; this file is the source of truth",
             f"file: {q(os.path.basename(stl))}",
             f"path: {q(rel)}",
             f"size_bytes: {meta['size']}",
             f"file_date: {meta['mtime']}  # filesystem mtime; may be data-rescue noise",
             f"described_by: {q(model) if model else 'null'}",
             f"described_on: {q(datetime.date.today().isoformat())}"]
    if vis:
        lines += [f"description: {q(vis['description'])}",
                  f"category: {q(vis['category'])}",
                  "tags: [" + ", ".join(q(t) for t in vis["tags"]) + "]"]
    lines += ["notes:            # yours — the model never touches this block",
              '  origin: ""      # when/why it was really made',
              '  for: ""         # who it was for',
              '  story: ""']
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--model", default="gemma4:12b")
    ap.add_argument("--no-vision", action="store_true")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--ollama", default="http://localhost:11434")
    args = ap.parse_args()

    root = os.path.abspath(args.folder)
    done = skipped = failed = no_collage = 0
    for dirpath, _, files in os.walk(root):
        for f in sorted(files):
            if not f.lower().endswith(".stl"):
                continue
            stl = os.path.join(dirpath, f)
            base = os.path.splitext(f)[0]
            sidecar = os.path.join(dirpath, base + ".stl.yaml")
            collage = os.path.join(dirpath, base + "-collage.png")
            if os.path.exists(sidecar):
                skipped += 1; continue
            if args.limit and done >= args.limit:
                print(f"limit {args.limit} reached"); report(done, skipped, failed, no_collage); return
            rel = os.path.relpath(stl, root).replace("\\", "/")
            st = os.stat(stl)
            meta = {"size": st.st_size,
                    "mtime": datetime.date.fromtimestamp(st.st_mtime).isoformat()}
            vis, model = None, None
            if not args.no_vision:
                if not os.path.exists(collage):
                    no_collage += 1
                    print(f"NOCOLLAGE {rel}"); continue
                try:
                    vis = parse_reply(vision(args.ollama, args.model, collage, f))
                    model = args.model
                except Exception as e:
                    failed += 1
                    print(f"FAIL {rel}: {e}", file=sys.stderr); continue
            write_yaml(sidecar, stl, rel, meta, vis, model)
            done += 1
            print(f"OK   {rel}" + (f"  [{vis['category']}]" if vis else ""))
    report(done, skipped, failed, no_collage)

def report(done, skipped, failed, no_collage):
    print("----")
    print(f"written: {done}  skipped(existing): {skipped}  failed: {failed}  missing-collage: {no_collage}")

if __name__ == "__main__":
    main()
